import * as fs from 'fs';
import * as path from 'path';

const base = path.resolve(__dirname, '..');
const read = (rel: string) => fs.readFileSync(path.resolve(base, rel), 'utf8');

const PRODUCTS_DIR = 'src/app/admin/inventory/products';
const FORM = `${PRODUCTS_DIR}/product-form.tsx`;
const LIST = 'src/components/inventory/products/products-workspace.tsx';
const NEW_ROUTE = `${PRODUCTS_DIR}/new/page.tsx`;
const EDIT_ROUTE = `${PRODUCTS_DIR}/[id]/edit/page.tsx`;
const DETAIL = `${PRODUCTS_DIR}/[id]/page.tsx`;
const ADAPTERS = 'src/components/f9/lookup-adapters.ts';
const BARREL = 'src/components/f9/index.ts';
const TYPES = 'src/lib/admin-types/inventory.ts';

/**
 * Product multi-UOM frontend contract. These assertions lock the ONE canonical
 * Product form (modal over the list), the global Unit lookup, the mandatory
 * explicit base row in the payload, and the legacy deep-link redirects.
 */
describe('Product multi-UOM frontend contract', () => {
  describe('global Unit adapter', () => {
    const adapters = read(ADAPTERS);
    const barrel = read(BARREL);

    it('declares exactly one global unit adapter bound to /units', () => {
      const matches = adapters.match(/export const unitAdapter/g) ?? [];
      expect(matches).toHaveLength(1);
      expect(adapters).toMatch(/unitAdapter[\s\S]*?endpoint:\s*'\/units'/);
      expect(adapters).toMatch(/unitAdapter[\s\S]*?detailEndpoint:\s*'\/units'/);
    });

    it('is human-readable and searches code/nameAr/nameEn', () => {
      expect(adapters).toMatch(/unitAdapter[\s\S]*?displayLabel:[^\n]*nameEn \|\| [^\n]*nameAr/);
      expect(adapters).toMatch(/unitAdapter[\s\S]*?searchFields:\s*\[[^\]]*'code'[^\]]*'nameAr'[^\]]*'nameEn'/);
    });

    it('is exported through the F9 barrel', () => {
      expect(BARREL && read(BARREL)).toContain('unitAdapter');
    });
  });

  describe('admin types', () => {
    const types = read(TYPES);
    it('exposes ProductUom and the Product unitId/unitRef/uoms surface', () => {
      expect(types).toContain('export interface ProductUom');
      expect(types).toMatch(/unitId\?:\s*string/);
      expect(types).toContain('unitRef?');
      expect(types).toMatch(/uoms\?:\s*ProductUom\[\]/);
    });
  });

  describe('canonical Product form', () => {
    const form = read(FORM);

    it('is the single form using the canonical Modal for create and edit', () => {
      expect(form).toContain("from '../../../../components/admin/ui'");
      expect(form).toContain('<Modal');
      expect(form).toContain('isEdit');
    });

    it('selects the base unit through the global unit adapter without free text', () => {
      expect(form).toMatch(/baseUnit[\s\S]*?adapter=\{unitAdapter\}/);
      expect(form).toContain('clearOnContextChange={false}');
    });

    it('ALWAYS includes the explicit base row in the uoms payload', () => {
      expect(form).toMatch(/uoms:\s*\[/);
      expect(form).toMatch(/unitId:\s*form\.unitId[\s\S]*?isBase:\s*true[\s\S]*?quantityPerParent:\s*1/);
    });

    it('does not force a code on create (backend owns numbering)', () => {
      expect(form).toMatch(/!form\.code\.trim\(\)/);
      expect(form).toContain('autoGeneratedIfBlank');
    });

    it('uses Unit IDs for parentUnitId (no ProductUom id knowledge required)', () => {
      expect(form).toContain('parentUnitId');
    });
  });

  describe('canonical Product list opening the modal in place', () => {
    const list = read(LIST);

    it('opens the same ProductForm for create and edit instead of navigating away', () => {
      expect(list).toContain("from '../../../app/admin/inventory/products/product-form'");
      expect(list).toContain('<ProductForm');
      expect(list).toContain('setFormProductId(null)');
      expect(list).toContain('setFormOpen(true)');
    });

    it('reads the deep-link query state safely', () => {
      expect(list).toContain("params.get('create')");
      expect(list).toContain("params.get('edit')");
      expect(list).toContain('window.history.replaceState');
    });
  });

  describe('legacy deep-link routes', () => {
    it('create route redirects to ?create=1', () => {
      expect(read(NEW_ROUTE)).toContain('/admin/inventory/products?create=1');
    });
    it('edit route redirects to ?edit=<id>', () => {
      expect(read(EDIT_ROUTE)).toContain('/admin/inventory/products?edit=');
    });
    it('does not re-implement a second form', () => {
      expect(read(NEW_ROUTE)).not.toContain('<Modal');
      expect(read(EDIT_ROUTE)).not.toContain('<Modal');
    });
  });

  describe('details page packaging hierarchy', () => {
    const detail = read(DETAIL);
    it('renders a read-only packaging hierarchy with derived conversion', () => {
      expect(detail).toContain('inventory.packagingHierarchy');
      expect(detail).toContain('conversionToBase');
      expect(detail).toContain('isBase');
    });
  });
});
