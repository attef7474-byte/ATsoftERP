const { PrismaClient } = require('@prisma/client');
const p = new PrismaClient();
(async () => {
  const user = await p.user.findFirst({ where: { email: 'admin@atsofterp.com' } });
  console.log('USER=' + user.id);
  const sp = await p.sparePart.findFirst({ where: { productId: { not: null } } });
  console.log('SPARE=' + sp.id);
  console.log('PROD=' + sp.productId);
  const sw = await p.warehouse.findFirst({ where: { warehouseType: 'SPARE_PART' } });
  console.log('SW=' + sw.id);
  const pw = await p.warehouse.findFirst({ where: { warehouseType: 'PRODUCT' } });
  console.log('PW=' + (pw ? pw.id : 'NONE'));
  const rw = await p.warehouse.findFirst({ where: { warehouseType: 'RAW_MATERIAL' } });
  console.log('RW=' + (rw ? rw.id : 'NONE'));
  const mr = await p.maintenanceRequest.findFirst();
  console.log('MR=' + (mr ? mr.id : 'NONE'));
  const ib = await p.inventoryBalance.findFirst({ where: { quantity: { gt: 0 } } });
  console.log('IB_PROD=' + (ib ? ib.productId : 'NONE'));
  console.log('IB_WH=' + (ib ? ib.warehouseId : 'NONE'));
  console.log('IB_QTY=' + (ib ? ib.quantity : 0));
  const mc = await p.machine.findFirst();
  console.log('MC=' + (mc ? mc.id : 'NONE'));
  console.log('MC_COMP=' + (mc ? mc.companyId : 'NONE'));
  console.log('MC_BR=' + (mc ? mc.branchId : 'NONE'));
  const seq = await p.numberSequence.findUnique({ where: { code: 'SPARE_PART_CONDITION_MOVEMENT' } });
  console.log('SEQ=' + (seq ? 'YES' : 'NO'));
  await p.$disconnect();
})().catch(e => { console.error(e.message); process.exit(1); });
