export type Phase6PermissionRecord = {
  key: string;
  module: string;
  action: string;
};

/**
 * PHASE 6 PERMISSION RECONCILIATION - canonical seed declarations for the 61
 * legacy permission keys that controllers enforce but the seed never declared.
 *
 * WHY THIS FILE EXISTS
 * --------------------
 * `PermissionsGuard` compares the requested key with an exact `Set.has`, and only
 * SUPER_ADMIN short-circuits the check. An enforced key that is absent from the
 * permission catalogue is therefore a route that is permanently 403 for every
 * non-SUPER_ADMIN role while still looking correct in a controller review.
 *
 * The R4R contract spec previously carried all 61 of these as reviewed
 * `KNOWN_UNSEEDED_LEGACY_KEYS` debt. Phase 6 eliminates that debt by declaring
 * every one of them here as a canonical, grantable key. Nothing is renamed or
 * removed: the singular keys generated by the MODULES x ACTIONS matrix and all
 * existing extraPermissions entries stay exactly as they were.
 *
 * ALIASES
 * -------
 * Several entries are the plural spelling of an already-seeded singular family
 * (`administrations:*` aliases `administration:*`, `branches:*` aliases
 * `branch:*`, `companies:*` aliases `company:*`, `roles:*` aliases `role:*`,
 * `permissions:read` aliases `permission:read`, `productionLines:*` aliases
 * `production-line:*`). Likewise the dotted feature keys are the guard spellings
 * of existing module families (`attachments.*` aliases `attachment:*`,
 * `notifications:*` aliases `notification:*`, `audit:read` aliases
 * `audit-log:read`, `settings:*` aliases `system-setting:*`,
 * `maintenance-task:*.view` aliases `maintenance-task:*`, etc.). They are seeded
 * under their enforced spelling because an exact `Set.has` match is required;
 * the pre-existing singular keys are kept as aliases and are not deprecated.
 */

