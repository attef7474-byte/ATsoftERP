/**
 * Split a key at its last separator so dotted keys keep their namespace in
 * `module` (e.g. `maintenance.dashboard.view` -> module `maintenance.dashboard`,
 * action `view`) while colon keys behave like every other seed entry.
 */
function toPermissionRecord(key: string): Phase6PermissionRecord {
  const separator = key.lastIndexOf(':') >= 0 ? ':' : '.';
  const index = key.lastIndexOf(separator);
  return {
    key,
    module: key.slice(0, index),
    action: key.slice(index + 1),
  };
}

/** Records fed into seed.ts `extraPermissions`; SUPER_ADMIN grant-all uses findMany(). */
export const PHASE6_GOVERNANCE_PERMISSIONS: Phase6PermissionRecord[] =
  PHASE6_GOVERNANCE_PERMISSION_KEYS.map(toPermissionRecord);
